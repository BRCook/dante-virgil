"""Configuration for chrony, ptp4l and phc2sys, generated for a Virgil's role.

Everything here is a pure function of its arguments, so it can be tested
without hardware. The values come from the prototype's reference build and the
settings used at the live show.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum

from virgil.nic_profiles import NicProfile


class Role(Enum):
    LEADER = "leader"
    FOLLOWER = "follower"


@dataclass(frozen=True)
class Tuning:
    """Settings shared by every Virgil in a group. The defaults are the prototype's."""

    # chrony, on followers
    maxdelayquant: float = 0.25
    minsamples: int = 64
    maxsamples: int = 256
    corrtimeratio: int = 20
    maxslewrate: int = 10
    # phc2sys, on followers
    phc2sys_kp: float = 0.03
    phc2sys_ki: float = 0.0005
    # ptp4l
    log_sync_interval: int = -3
    log_announce_interval: int = 1
    log_min_delay_req_interval: int = -3


DEFAULT_TUNING = Tuning()

CHRONY_DRIFTFILE = "/var/lib/chrony/chrony.drift"


@dataclass(frozen=True)
class TimingSetup:
    """What the generated configuration needs to know about this Virgil."""

    ptp_interface: str
    # None when the PTP interface only has software timestamping.
    phc: str | None
    profile: NicProfile | None = None
    trim_ppb: int = 0

    @property
    def hardware(self) -> bool:
        return self.phc is not None


def ptp4l_conf(setup: TimingSetup, tuning: Tuning = DEFAULT_TUNING) -> str:
    """ptp4l's config. It's the same in both roles, so a role change never restarts ptp4l."""
    lines = [
        "[global]",
        "# Generated by Virgil. Changes here will be overwritten.",
        "domainNumber            0",
        "priority1               1",
        "serverOnly              1",
        "network_transport       UDPv4",
        "ptp_minor_version       0",
        f"logSyncInterval         {tuning.log_sync_interval}",
        f"logAnnounceInterval     {tuning.log_announce_interval}",
        f"logMinDelayReqInterval  {tuning.log_min_delay_req_interval}",
        "tx_timestamp_timeout    50",
    ]
    if not setup.hardware:
        lines.append("time_stamping           software")
    lines += ["", f"[{setup.ptp_interface}]", ""]
    return "\n".join(lines)


def _chrony_common() -> list[str]:
    return [
        "# Generated by Virgil. Changes here will be overwritten.",
        f"driftfile {CHRONY_DRIFTFILE}",
        "rtcsync",
    ]


def chrony_leader_conf(setup: TimingSetup, allow: list[str]) -> str:
    """chrony on the leader: the system clock follows the PHC, and is served to the group."""
    lines = _chrony_common()
    lines += [
        "",
        "# Serve this Virgil's clock to the group, with no other source",
        "local stratum 1",
    ]
    lines += [f"allow {address}" for address in allow]
    if setup.hardware:
        lines.append(f"refclock PHC {setup.phc} poll 0 dpoll -2 prefer")
    lines += ["makestep 1 3", ""]
    return "\n".join(lines)


def chrony_follower_conf(leader: str, allow: list[str], tuning: Tuning = DEFAULT_TUNING) -> str:
    """chrony on a follower: follow the leader, keeping only the fastest round trips."""
    lines = _chrony_common()
    lines += [
        "",
        "# Follow the leader over the link, keeping only the fastest round trips",
        (
            f"server {leader} iburst minpoll 0 maxpoll 0 xleave"
            f" maxdelayquant {tuning.maxdelayquant}"
            f" minsamples {tuning.minsamples} maxsamples {tuning.maxsamples}"
        ),
        "authselectmode ignore",
        f"corrtimeratio {tuning.corrtimeratio}",
        f"maxslewrate {tuning.maxslewrate}",
        "makestep 0.001 -1",
        "",
        "# Let other members take their boot time from this Virgil.",
        "# No 'local stratum': a follower never vouches for time it doesn't have.",
    ]
    lines += [f"allow {address}" for address in allow]
    lines.append("")
    return "\n".join(lines)


def chrony_conf(role: Role, setup: TimingSetup, allow: list[str], leader: str | None = None,
                tuning: Tuning = DEFAULT_TUNING) -> str:
    if role is Role.LEADER:
        return chrony_leader_conf(setup, allow)
    if leader is None:
        raise ValueError("a follower needs a leader")
    return chrony_follower_conf(leader, allow, tuning)


def phc2sys_args(setup: TimingSetup, tuning: Tuning = DEFAULT_TUNING) -> list[str] | None:
    """phc2sys's arguments on a follower, or None if phc2sys shouldn't run."""
    if not setup.hardware:
        return None
    return [
        "-s", "CLOCK_REALTIME",
        "-c", setup.phc,
        "-O", "0",
        "-P", str(tuning.phc2sys_kp),
        "-I", str(tuning.phc2sys_ki),
        "-S", "0.001",
        "-m",
        "-q",
    ]


def hwstamp_ctl_args(setup: TimingSetup) -> list[str] | None:
    """hwstamp_ctl's arguments, for drivers that need it before the PHC runs."""
    if not setup.hardware or setup.profile is None or not setup.profile.needs_hwstamp_ctl:
        return None
    return ["-i", setup.ptp_interface, *setup.profile.hwstamp_ctl_args]


@dataclass(frozen=True)
class Command:
    args: tuple[str, ...]
    # A command that may fail without stopping the ones after it.
    may_fail: bool = False


def sync_commands(setup: TimingSetup, leader: str | None) -> list[Command]:
    """The commands that prepare the clocks before the timing services start.

    Take the time from the leader if there is one (giving up after 20 s), start
    the PHC if its driver needs it, set the PHC to the system clock, then run it
    at the Virgil's trim rate. A failure to reach the leader isn't fatal: the Virgil
    keeps its own clock.
    """
    commands: list[Command] = []
    if leader is not None:
        commands.append(
            Command(("/usr/sbin/chronyd", "-q", "-t", "20", f"server {leader} iburst"), may_fail=True)
        )
    if not setup.hardware:
        return commands
    hwstamp = hwstamp_ctl_args(setup)
    if hwstamp is not None:
        commands.append(Command(("/usr/sbin/hwstamp_ctl", *hwstamp)))
    commands.append(Command(("/usr/sbin/phc_ctl", setup.phc, "set")))
    commands.append(Command(("/usr/sbin/phc_ctl", setup.phc, "freq", str(setup.trim_ppb))))
    return commands
