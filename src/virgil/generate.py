"""Configuration for chrony, ptp4l and phc2sys, generated for a Virgil's role.

Everything here is a pure function of its arguments, so it can be tested
without hardware. The values come from the prototype's reference build and the
settings used at the live show.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum

from virgil.nic_profiles import NicProfile


class Role(Enum):
    LEADER = "leader"
    FOLLOWER = "follower"


@dataclass(frozen=True)
class Tuning:
    """Settings shared by every Virgil in a group. The defaults are the prototype's."""

    # chrony, on followers
    maxdelayquant: float = 0.25
    # Chrony keeps at most 64 samples per source, whatever these say (its useful range is 4 to 64), so both are 64:
    # the prototype's maxsamples 256 never did anything.
    minsamples: int = 64
    maxsamples: int = 64
    # How many measurements chrony merges into each sample, by their median (1: each measurement is a sample). With
    # 64 samples at most, merging makes each one cleaner and the history longer, so the rate estimate jumps less.
    filter: int = 8
    corrtimeratio: int = 20
    maxslewrate: int = 10
    # phc2sys, on followers
    phc2sys_kp: float = 0.03
    phc2sys_ki: float = 0.0005
    # ptp4l
    log_sync_interval: int = -3
    log_announce_interval: int = 1
    log_min_delay_req_interval: int = -3


DEFAULT_TUNING = Tuning()

CHRONY_DRIFTFILE = "/var/lib/chrony/chrony.drift"


@dataclass(frozen=True)
class TimingSetup:
    """What the generated configuration needs to know about this Virgil."""

    ptp_interface: str
    # None when the PTP interface only has software timestamping.
    phc: str | None
    profile: NicProfile | None = None
    trim_ppb: int = 0

    @property
    def hardware(self) -> bool:
        return self.phc is not None


def ptp4l_conf(setup: TimingSetup, tuning: Tuning = DEFAULT_TUNING) -> str:
    """ptp4l's config. It's the same in both roles, so a role change never restarts ptp4l."""
    lines = [
        "[global]",
        "# Generated by Virgil. Changes here will be overwritten.",
        "domainNumber            0",
        "priority1               1",
        "serverOnly              1",
        "network_transport       UDPv4",
        "ptp_minor_version       0",
        f"logSyncInterval         {tuning.log_sync_interval}",
        f"logAnnounceInterval     {tuning.log_announce_interval}",
        f"logMinDelayReqInterval  {tuning.log_min_delay_req_interval}",
        "tx_timestamp_timeout    50",
        "# Answer unicast Delay Requests with unicast Delay Responses; multicast ones stay multicast.",
        "hybrid_e2e              1",
        "# Mark PTP as CS7, as Dante does, so switches with QoS give it the same priority.",
        "dscp_event              56",
        "dscp_general            56",
    ]
    if not setup.hardware:
        lines.append("time_stamping           software")
    lines += ["", f"[{setup.ptp_interface}]", ""]
    return "\n".join(lines)


def _chrony_common() -> list[str]:
    return [
        "# Generated by Virgil. Changes here will be overwritten.",
        f"driftfile {CHRONY_DRIFTFILE}",
        "rtcsync",
    ]


def _hwtimestamp(interface: str | None) -> list[str]:
    """Timestamp NTP packets in the NIC, which cuts a follower's jitter a long way."""
    if interface is None:
        return []
    return ["", "# NTP timestamps from the management interface's hardware", f"hwtimestamp {interface} rxfilter all"]


# The group's NTP keys, for chrony (see virgil.ntpauth). Written by virgil-root prepare.
KEYFILE = "/run/dante-virgil-generated/chrony.keys"


def chrony_keys(keys: list[tuple[int, str]]) -> str:
    """chrony's key file: each key as an HMAC-SHA256 key, in hex."""
    return "".join(f"{key_id} SHA256 HEX:{key}\n" for key_id, key in keys)


def _keyfile(keyfile: str | None) -> list[str]:
    if keyfile is None:
        return []
    return ["", "# The group's NTP keys: every NTP packet between members is signed with one", f"keyfile {keyfile}"]


def chrony_leader_conf(setup: TimingSetup, allow: list[str], hwtimestamp: str | None = None,
                       keyfile: str | None = None) -> str:
    """chrony on the leader: the system clock follows the PHC, and is served to the group. With a key file, it
    answers a follower's signed request with the same key, so a follower can tell its replies from forged ones."""
    lines = _chrony_common() + _hwtimestamp(hwtimestamp) + _keyfile(keyfile)
    lines += [
        "",
        "# Serve this Virgil's clock to the group, with no other source",
        "local stratum 1",
    ]
    lines += [f"allow {address}" for address in allow]
    if setup.hardware:
        lines.append(f"refclock PHC {setup.phc} poll 0 dpoll -2 prefer")
    lines += ["makestep 1 3", ""]
    return "\n".join(lines)


def chrony_follower_conf(leader: str, allow: list[str], tuning: Tuning = DEFAULT_TUNING,
                         hwtimestamp: str | None = None, keyfile: str | None = None,
                         key_id: int | None = None) -> str:
    """chrony on a follower: follow the leader, keeping only the fastest round trips. With a key, it signs its
    requests, and ignores any reply not signed with the same key, so nobody can forge the leader's time."""
    lines = _chrony_common() + _hwtimestamp(hwtimestamp) + _keyfile(keyfile if key_id is not None else None)
    lines += [
        "",
        "# Follow the leader over the link, keeping only the fastest round trips",
        (
            f"server {leader} iburst minpoll 0 maxpoll 0 xleave"
            f" maxdelayquant {tuning.maxdelayquant}"
            f" minsamples {tuning.minsamples} maxsamples {tuning.maxsamples}"
            + (f" filter {tuning.filter}" if tuning.filter > 1 else "")
            + (f" key {key_id}" if key_id is not None else "")
        ),
        "authselectmode require" if key_id is not None else "authselectmode ignore",
        f"corrtimeratio {tuning.corrtimeratio}",
        f"maxslewrate {tuning.maxslewrate}",
        "makestep 0.001 -1",
        "",
        "# Let other members take their boot time from this Virgil.",
        "# No 'local stratum': a follower never vouches for time it doesn't have.",
    ]
    lines += [f"allow {address}" for address in allow]
    lines.append("")
    return "\n".join(lines)


def chrony_conf(role: Role, setup: TimingSetup, allow: list[str], leader: str | None = None,
                tuning: Tuning = DEFAULT_TUNING, hwtimestamp: str | None = None, keyfile: str | None = None,
                key_id: int | None = None) -> str:
    if role is Role.LEADER:
        return chrony_leader_conf(setup, allow, hwtimestamp, keyfile)
    if leader is None:
        raise ValueError("a follower needs a leader")
    return chrony_follower_conf(leader, allow, tuning, hwtimestamp, keyfile, key_id)


def phc2sys_args(setup: TimingSetup, tuning: Tuning = DEFAULT_TUNING) -> list[str] | None:
    """phc2sys's arguments on a follower, or None if phc2sys shouldn't run."""
    if not setup.hardware:
        return None
    return [
        "-s", "CLOCK_REALTIME",
        "-c", setup.phc,
        "-O", "0",
        "-P", str(tuning.phc2sys_kp),
        "-I", str(tuning.phc2sys_ki),
        "-S", "0.001",
        # Never step on the first update either (by default, phc2sys steps then if off by more than 20 µs): a
        # restart, or a Clock Box becoming a follower, would otherwise make the PHC (and the Dante devices'
        # grandmaster) jump by tens of microseconds. Over 1 ms (-S) is still stepped.
        "-F", "0",
        "-m",
        "-q",
    ]


def hwstamp_ctl_args(setup: TimingSetup) -> list[str] | None:
    """hwstamp_ctl's arguments, for drivers that need it before the PHC runs."""
    if not setup.hardware or setup.profile is None or not setup.profile.needs_hwstamp_ctl:
        return None
    return ["-i", setup.ptp_interface, *setup.profile.hwstamp_ctl_args]


@dataclass(frozen=True)
class Command:
    args: tuple[str, ...]
    # A command that may fail without stopping the ones after it.
    may_fail: bool = False


# Saving the system time to the hardware clock, so an offline boot starts near the right time.
# Not every machine has one, so it may fail.
HWCLOCK = Command(("/usr/sbin/hwclock", "--systohc"), may_fail=True)


def sync_commands(setup: TimingSetup, leader: str | None, keyfile: str | None = None,
                  key_id: int | None = None) -> list[Command]:
    """The commands that prepare the clocks before the timing services start.

    Take the time from the leader if there is one (giving up after 20 s), start
    the PHC if its driver needs it, set the PHC to the system clock, then run it
    at the Virgil's trim rate. A failure to reach the leader isn't fatal: the Virgil
    keeps its own clock.
    """
    commands: list[Command] = []
    if leader is not None:
        # Given directives, chronyd -q reads only those, not chrony.conf: so the key file and key go here too, or
        # setting the clock would be the one step anyone could forge.
        directives = (f"keyfile {keyfile}", f"server {leader} iburst key {key_id}") if key_id is not None \
            else (f"server {leader} iburst",)
        commands.append(Command(("/usr/sbin/chronyd", "-q", "-t", "20", *directives), may_fail=True))
    if not setup.hardware:
        return commands + ([HWCLOCK] if leader is not None else [])
    hwstamp = hwstamp_ctl_args(setup)
    if hwstamp is not None:
        commands.append(Command(("/usr/sbin/hwstamp_ctl", *hwstamp)))
    # "--" ends phc_ctl's options, so a negative trim isn't read as one.
    commands.append(Command(("/usr/sbin/phc_ctl", setup.phc, "--", "set")))
    commands.append(Command(("/usr/sbin/phc_ctl", setup.phc, "--", "freq", str(setup.trim_ppb))))
    commands.append(HWCLOCK)
    return commands


def trim_command(setup: TimingSetup) -> Command | None:
    """Set the PHC's frequency to the trim, without touching its time. None without a PHC."""
    if not setup.hardware:
        return None
    # "--" ends phc_ctl's options, so a negative trim isn't read as one.
    return Command(("/usr/sbin/phc_ctl", setup.phc, "--", "freq", str(setup.trim_ppb)))
